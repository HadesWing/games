/** 按纬度挑一条知识：热带 / 温带 / 寒带 */
export function pickFact(lat) {
  const a = Math.abs(lat);
  let pool;
  if (a < 23.5) pool = FACTS.tropical;
  else if (a < 66.5) pool = FACTS.temperate;
  else pool = FACTS.polar;
  if (Math.random() < 0.65) return pool[Math.floor(Math.random() * pool.length)];
  return FACTS.any[Math.floor(Math.random() * FACTS.any.length)];
}
