// 反查索引：词 → { category, cluster, clusterIndex, wordIndex }
export const INDEX = (() => {
  const map = new Map()
  for (const [category, clusters] of Object.entries(GRAPH)) {
    const names = Object.keys(clusters)
    names.forEach((cluster, clusterIndex) => {
      clusters[cluster].forEach((word, wordIndex) => {
        if (!map.has(word)) map.set(word, { category, cluster, clusterIndex, wordIndex, size: clusters[cluster].length })
      })
    })
  }
  return map
})()

// 可作为题目的词：2–3 字，且在图谱内
export const ANSWER_POOL = (() => {
  const pool = []
  for (const [category, clusters] of Object.entries(GRAPH)) {
    for (const words of Object.values(clusters)) {
      for (const w of words) {
        const n = [...w].length
        if (n >= 2 && n <= 3) pool.push({ answer: w, category })
      }
    }
  }
  return pool
})()

